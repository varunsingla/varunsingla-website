def spotlight_problems(pdf_name: str, viral) -> list[str]:
    """What is wrong with the spotlight a fresh parse of this PDF produced."""
    problems = []
    viral = viral or {}
    desc = viral.get('description') or ''
    if desc and not _SENTENCE_END.search(desc.strip()) and pdf_name not in UNPUNCTUATED_SPOTLIGHTS:
        problems.append(f"{pdf_name}: spotlight description stops mid-sentence: …{desc[-60:]!r}")
    want = KNOWN_BOXES.get(pdf_name)
    if want:
        if viral.get('name') != want['name']:
            problems.append(f"{pdf_name}: spotlight name is {viral.get('name')!r}, expected {want['name']!r}")
        if not desc.startswith(want['starts']):
            problems.append(f"{pdf_name}: spotlight description starts {desc[:70]!r}…, expected {want['starts'][:70]!r}…")
        if not desc.endswith(want['ends']):
            problems.append(f"{pdf_name}: spotlight description ends …{desc[-70:]!r}, expected …{want['ends'][-70:]!r}")
        if len(desc) != want['length']:
            problems.append(f"{pdf_name}: spotlight description is {len(desc)} characters, expected {want['length']}")
    return problems


