#!/usr/bin/env python3
"""
check_learnings.py — regression check: no page furniture in the published text.

The daily PDF prints a running header/footer on every page. When the parser
does not recognise one, it gets joined into whatever paragraph, takeaway, quiz
answer or sources line spans the page break and is published mid-sentence:

    ...is the agent version of a corporate card AI Learning -- Day 239 |
    2026-11-22 | Page 3 with a manager sign-off.

This script fails (exit code 1) when any of these is found:

    AI Learning -- Day N | YYYY-MM-DD | Page N
    Daily AI Learning for Varun AI Learning -- Day N | YYYY-MM-DD | Page N
    Daily AI Learning for Varun
    D&O;  R&D;  S&P;      an ampersand the PDF generator turned into a broken
                          HTML entity (should read D&O, R&D, S&P)
    &gt;threshold         "&gt;" / "&lt;" printed as literal text (should read
                          ">threshold")

and the page furniture of the layouts before 2026-10-16 -- running footers,
the sign-off line under the last paragraph, the masthead and byline of page 1:

    Varun Singla · Daily AI Learning Page N       Varun Singla · AI Learning Journal Page N
    Varun Singla · Daily AI Learning · Page N     Varun Singla Page N
    Generated by Varun Singla · varunsingla.com · Day N · <date>
    Generated for varunsingla.com · Daily AI Learning
    Generated by Daily AI Learning · varunsingla.com · Day N
    AI Daily Learning | Varun Singla | Day N | <date>
    AI Daily Learning | Varun Singla Page N | <date>
    AI Daily Learning · Day N · Issue #N · YYYY-MM-DD Page N · varunsingla.com
    Daily AI Learning · Day N · <date> Page N
    AI DAILY LEARNING • Day N • <the day's topic> <date>
    varunsingla.com · Agentic AI Daily
    varunsingla.com · Daily learning brief · Built with Claude in Cowork mode
    Generated for <e-mail address> · Issue #N · varunsingla.com
    Varun's Daily AI Brief Day N · <date> · Issue #N      (and "Briefing",
        "Intelligence", "AI Learning Brief", "AI Learning Series", some of
        them with an e-mail address or a "| Topics: …" list)
    Generated by Claude AI | Topics sourced from …
    Day N · <date> · Varun Singla's AI Learning Journal
    <date> · Curated for Varun Singla             <date> | Edition for Varun Singla

A sentence that merely mentions the author, the site or the series is fine
("Why it matters for you, Varun: …"); what is forbidden is the name next to a
page number, a separator (· • |) or a footer field.

It looks in three places:
  1. every string stored in learnings.json;
  2. the generated pages (entries/*.html and the other derived files);
  3. a fresh parse of the newest PDF, which must also be free of every line
     the PDF itself prints in its page margins, whatever that line says.
     PDFs from before 2026-10-16 still parse with a footer in a few fields (the
     parser for those layouts is unchanged on purpose), so for the older
     wordings it is the entry as it would be stored -- the parse after
     scrub_entry -- that has to be clean.

Run:
    python3 check_learnings.py              the three checks above (a few seconds)
    python3 check_learnings.py --all-pdfs   re-parse every PDF on disk (about two minutes)
    python3 check_learnings.py A.pdf B.pdf  re-parse these PDFs as well

The shapes are written out here on purpose rather than imported from
update_site.py: the check states what must never be published, independently
of how the parser and the repair pass go about removing it.
"""

