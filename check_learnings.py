# The three footer shapes. The second is the first two back to back (the footer
# of one page followed by the header of the next), so two patterns cover all three.
FOOTER_RE = re.compile(
    r'AI Learning -- Day \d+ \| \d{4}-\d{2}-\d{2} \| Page \d+'
    r'|Daily AI Learning for Varun')

# Page furniture of the older layouts (2026-03-15 … 2026-08-29). Stated here as
# what such a line looks like, not as the exact wordings the repair pass
# removes: the author, the site or the series name next to a page number, a
# separator or another footer field. Each alternative is one kind of line.
_APOS = r"(?:['’]|&#x27;|&#39;)"              # an apostrophe, as stored or as escaped in the generated HTML
_SEP = r'[·•|]'                               # what these footers put between their fields
OLD_FURNITURE_RE = re.compile('|'.join([
    # the author's name, perhaps a few footer fields, then a page number
    r'Varun Singla(?:[^.!?\n]|\.(?=\w)){0,70}?\bPage \d+',
    # the series name with a footer field after it
    rf'(?:Daily AI Learning|AI Daily Learning|AI DAILY LEARNING) {_SEP} (?:Day \d|Issue\b|Varun Singla|Page \d)',
    rf'AI Daily Learning [A-Z][a-z]+ \d{{1,2}}, \d{{4}} {_SEP}',
    # the site name between footer fields
    rf'varunsingla\.com {_SEP} (?:Agentic AI Daily|Daily learning brief|Daily AI Learning|Day \d)',
    rf'(?:Page \d+|Issue #?\d+|Varun Singla) {_SEP} varunsingla\.com',
    # "Generated by / for …": the credit line under the last paragraph
    r'Generated (?:by|for) (?:Varun Singla|varunsingla\.com|Daily AI Learning|[\w.+-]+@)',
    r'Generated by Claude AI \|',
    r'Built with Claude in Cowork mode',
    # masthead and byline of page 1 (the site's own name, "Varun Singla · AI Learning Journal", is not one)
    rf'{_SEP} Varun Singla{_APOS}s (?:AI Learning Journal|Daily AI Learning)',
    r'(?:Curated|Edition|Prepared) for Varun Singla',
    # the series names of March–May, followed by a separator
    rf'Varun{_APOS}s (?:Daily AI (?:Brief|Briefing|Intelligence)|AI Learning (?:Brief|Series))(?: Day \d+)? (?:{_SEP}|--) ',
]))

# "&gt;threshold" — a "<" or ">" that reached the page as its HTML entity (a
# table cell is plain text to the PDF generator, so the entity is printed as
# written). In the generated HTML/XML the same artefact arrives escaped once
# more, as "&amp;gt;"; a plain "&gt;" there is just an escaped ">".
_ENTITY_RE = re.compile(r'&(?:gt|lt);')
_ENTITY_ESCAPED_RE = re.compile(r'&amp;(?:gt|lt);')

# "D&O;" — a letter or digit, an ampersand, a name and a semicolon. This is
# what ReportLab prints for a bare "&" ("D&O insurance" -> "D&O; insurance",
# "Q&A." -> "Q&A.;", "R&D-heavy" -> "R&D-heavy;"). Real HTML entities (&amp;
# &gt; &Pi; …) are not this artefact. In the generated HTML/XML the same
# artefact arrives escaped, as "D&amp;O;".
_AMP_RE = re.compile(r'(?<=[A-Za-z0-9])&([A-Za-z][-.A-Za-z0-9]{0,23});')
_AMP_ESCAPED_RE = re.compile(r'(?<=[A-Za-z0-9])&amp;([A-Za-z][-.A-Za-z0-9]{0,23});')

GENERATED = ['entries/*.html', 'weekly/*.html', 'index.html', 'playbook/index.html',
             'concepts/index.html', 'watching/index.html', 'start/index.html',
             'review/index.html', 'index.json', 'search.json', 'feed.xml',
             'llms.txt', 'llms-full.txt']


def mangled_amps(text: str, escaped: bool = False) -> list[str]:
    return [m.group(0) for m in (_AMP_ESCAPED_RE if escaped else _AMP_RE).finditer(text)
            if m.group(1) + ';' not in html.entities.html5]


def walk(obj, path=()):
    """Yield (path, string) for every string inside a JSON value."""
    if isinstance(obj, str):
        yield path, obj
    elif isinstance(obj, dict):
        for key, value in obj.items():
            yield from walk(value, path + (key,))
    elif isinstance(obj, list):
        for i, value in enumerate(obj):
            yield from walk(value, path + (i,))


def offences(obj, label: str, raw_parse: bool = False) -> list[str]:
    """Human-readable list of every footer / mangled ampersand / literal
    entity inside obj. raw_parse=True looks only for what the parser itself
    takes out (the current layout's running lines, mangled ampersands); the
    older wordings and literal entities are the repair pass's to remove."""
    found = []
    for path, text in walk(obj):
        where = f"{label} {'/'.join(map(str, path))}".strip()
        for m in FOOTER_RE.finditer(text):
            before = text[max(0, m.start() - 30):m.start()]
            found.append(f"{where}: footer {m.group(0)!r} after {before!r}")
        for amp in mangled_amps(text):
            found.append(f"{where}: mangled ampersand {amp!r}")
        if raw_parse:
            continue
        for m in OLD_FURNITURE_RE.finditer(text):
            before = text[max(0, m.start() - 30):m.start()]
            found.append(f"{where}: older page furniture {text[m.start():m.end() + 30]!r} after {before!r}")
        for m in _ENTITY_RE.finditer(text):
            found.append(f"{where}: literal entity {text[max(0, m.start() - 20):m.end() + 12]!r}")
    return found


def report(name: str, problems: list[str]) -> bool:
    if not problems:
        print(f"  ok    {name}")
        return True
    print(f"  FAIL  {name}: {len(problems)} problem(s)")
    for p in problems[:12]:
        print(f"          {p}")
    if len(problems) > 12:
        print(f"          … and {len(problems) - 12} more")
    return False


# ── 1. Stored entries ─────────────────────────────────────────────────────────

def check_stored() -> list[str]:
    data = json.loads((ROOT / 'learnings.json').read_text(encoding='utf-8'))
    problems = []
    for entry in data.get('learnings', []):
        problems.extend(offences(entry, entry.get('date', '?')))
    return problems


# ── 2. Generated pages ────────────────────────────────────────────────────────

def check_generated() -> list[str]:
    problems = []
    for pattern in GENERATED:
        for path in sorted(ROOT.glob(pattern)):
            text = path.read_text(encoding='utf-8', errors='replace')
            rel = path.relative_to(ROOT)
            escaped = path.suffix not in ('.txt', '.json')
            n = len(FOOTER_RE.findall(text))
            if n:
                problems.append(f"{rel}: {n} footer string(s), e.g. {FOOTER_RE.search(text).group(0)!r}")
            old = [m.group(0) for m in OLD_FURNITURE_RE.finditer(text)]
            if old:
                problems.append(f"{rel}: {len(old)} piece(s) of older page furniture, e.g. {old[0]!r}")
            amps = mangled_amps(text, escaped=escaped)
            if amps:
                problems.append(f"{rel}: {len(amps)} mangled ampersand(s), e.g. {amps[0]!r}")
            entities = (_ENTITY_ESCAPED_RE if escaped else _ENTITY_RE).findall(text)
            if entities:
                problems.append(f"{rel}: {len(entities)} literal entit{'y' if len(entities) == 1 else 'ies'}, e.g. {entities[0]!r}")
    return problems


