def _pages(*pages, styled: bool = True) -> list[dict]:
    """Pages as the parser holds them: the text lines, and each line's style.
    A row is 'text' (body type) or ('text', style)."""
    out = []
    for rows in pages:
        lines, styles = [], {}
        for row in rows:
            text, style = (row, _BODY) if isinstance(row, str) else row
            lines.append(text)
            if styled:
                styles[text] = style
        out.append({'lines': lines, 'styles': styles, 'tables': []})
    return out


