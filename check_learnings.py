def check_pdf(U, pdf: Path) -> list[str]:
    """A fresh parse of one PDF: none of the known shapes, and none of the
    lines the parser itself classifies as running header/footer. The wordings
    of the older layouts are looked for in the entry as it would be stored
    (after scrub_entry): the parser still lets a few of them through."""
    with contextlib.redirect_stdout(io.StringIO()):
        entry = U.parse_pdf(pdf)
        flat = U._flat_lines_for_repair(pdf)
        repair = {'sources': U.extract_sources(flat), 'tomorrow_preview': U.extract_tomorrow_block(flat),
                  'recap': U.extract_recap(flat), 'quiz': U.extract_quiz(flat)}
    problems = (offences(entry, f"parse of {pdf.name}:", raw_parse=True)
                + offences(repair, f"repair extractors on {pdf.name}:", raw_parse=True))
    problems += quiz_in_takeaways(entry, f"parse of {pdf.name}:") + repeated_in_takeaways(entry, f"parse of {pdf.name}:")
    stored = copy.deepcopy({'parse': entry, 'repair': repair})
    U.scrub_entry(stored)
    problems += offences(stored, f"{pdf.name} as it would be stored:")
    # A market signal or watch list stored twice is the repair pass's to bring
    # back to one copy as well (the 2026-07-03 PDF still parses with its
    # "Tomorrow's Preview" at the end of the last takeaway), so that too is
    # looked for in the entry as it would be stored.
    if hasattr(U, 'dedupe_blocks'):
        U.dedupe_blocks(stored['parse'])
        problems += repeated_blocks(stored['parse'], f"{pdf.name} as it would be stored:")
    if not hasattr(U, 'running_lines'):
        return problems + ['update_site.py has no running_lines']
    for line in sorted(set(U.running_lines(pdf))):
        hits = [f"{'/'.join(map(str, path))}" for path, text in walk({'parse': entry, 'repair': repair}) if line in text]
        if hits:
            problems.append(f"{pdf.name}: margin line {line!r} is in {', '.join(hits[:4])}")
    if not entry.get('title'):
        problems.append(f"{pdf.name}: the parse came back empty")
    problems.extend(spotlight_problems(pdf.name, entry.get('viral_app')))
    return problems


